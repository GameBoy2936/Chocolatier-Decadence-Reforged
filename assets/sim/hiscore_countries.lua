-- Flags pinned to the first selector page for quick access.  Keep this list
-- short enough to fit one 3 x 7 page; the remaining countries follow in the
-- registry's normal alphabetical order without duplicates.
HighScoreCountries.commonCodes = {
	"usa", "uk", "canada", "australia", "new_zealand", "ireland",
	"france", "germany", "italy", "spain", "netherlands", "sweden",
	"japan", "korea_south", "china", "india", "philippines", "indonesia",
	"brazil", "mexico", "south_africa",
}

function HighScoreCountries:IsCommon(code)
	for _, commonCode in ipairs(self.commonCodes) do
		if commonCode == code then return true end
	end
	return false
end

function HighScoreCountries:GetSelectorEntries()
	local result = {}

	-- First page: common choices in a deliberate quick-access order.
	for _, code in ipairs(self.commonCodes) do
		local country = self:Get(code)
		if country then table.insert(result, country) end
	end

	-- Everything else follows once, retaining the registry's alphabetical order.
	for _, country in ipairs(self.entries) do
		if not self:IsCommon(country.code) then
			table.insert(result, country)
		end
	end

	return result
end

function HighScoreCountries:Get(code)
	if not code or code == "" then return nil end
	for _, country in ipairs(self.entries) do
		if country.code == code then return country end
	end
	return nil
end

function HighScoreCountries:IsValid(code)
	if code == nil or code == "" then return true end
	return self:Get(code) ~= nil
end

function HighScoreCountries:GetName(code)
	local country = self:Get(code)
	if not country then return GetString("hiscore_country_none") end
	return GetString(country.key)
end

function HighScoreCountries:GetFlag(code)
	local country = self:Get(code)
	if not country then return "" end
	return "image/flags/flag_" .. country.code
end
